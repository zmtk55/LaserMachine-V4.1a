-- ============================================================
-- LaserMachine — Esquema Supabase (PostgreSQL)
-- ============================================================
-- CÓMO USARLO (el dueño, a mano, en el panel de Supabase):
--   1. Supabase Dashboard > SQL Editor > New query
--   2. Pegar TODO este archivo y pulsar Run.
--   3. Verificar en Table Editor que existen las 4 tablas.
--
-- Esto NO se puede hacer desde el código de la app: la creación de
-- tablas y el RLS solo se gestionan desde el panel de Supabase.
-- Sin estas tablas la app sigue funcionando con localStorage
-- (degrada con gracia), pero los pedidos de los clientes no llegan
-- a ningún lado compartido.
--
-- TABLAS: products, orders, fonts, store_config
-- Las columnas snake_case coinciden con lo que lee/escribe
-- services/supabaseService.ts. Los datos anidados (colores del
-- producto, items del pedido, configuración completa) van en JSONB.
-- ============================================================

-- ------------------------------------------------------------
-- 1. products — catálogo (los colores van en JSONB)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.products (
  id               TEXT PRIMARY KEY,
  name             TEXT NOT NULL,
  brand            TEXT NOT NULL,
  category         TEXT,
  price            NUMERIC(10,2) NOT NULL DEFAULT 0,
  stock_threshold  INTEGER NOT NULL DEFAULT 0,
  image_url        TEXT,
  colors           JSONB NOT NULL DEFAULT '[]'::jsonb,
  laser_preset_id  TEXT,
  sku              TEXT,
  is_active        BOOLEAN NOT NULL DEFAULT true,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- 2. orders — pedidos (los items y el historial van en JSONB)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.orders (
  id                TEXT PRIMARY KEY,
  user_id           TEXT NOT NULL DEFAULT 'guest',
  customer_name     TEXT NOT NULL,
  customer_company  TEXT,
  customer_phone    TEXT NOT NULL,
  customer_email    TEXT,
  items             JSONB NOT NULL DEFAULT '[]'::jsonb,
  coupon_used       TEXT,
  discount_amount   NUMERIC(10,2),
  points_redeemed   INTEGER,
  points_earned     INTEGER,
  total             NUMERIC(10,2) NOT NULL DEFAULT 0,
  payment_status    TEXT NOT NULL,
  payment_method    TEXT,
  amount_paid       NUMERIC(10,2) NOT NULL DEFAULT 0,
  delivery_method   TEXT,
  delivery_date     TEXT,
  delivery_time     TEXT,
  shipping_provider TEXT,
  shipping_tracking TEXT,
  shipping_address  TEXT,
  status            TEXT NOT NULL,
  is_priority       BOOLEAN NOT NULL DEFAULT false,
  history           JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  mockup_url        TEXT,
  internal_notes    JSONB,
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS orders_customer_phone_idx ON public.orders (customer_phone);
CREATE INDEX IF NOT EXISTS orders_created_at_idx ON public.orders (created_at DESC);

-- ------------------------------------------------------------
-- 3. fonts — tipografías (file_data puede ser base64 grande)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.fonts (
  id          BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name        TEXT NOT NULL,
  css_family  TEXT NOT NULL,
  category    TEXT,
  categories  JSONB,
  is_custom   BOOLEAN NOT NULL DEFAULT false,
  file_data   TEXT,
  preview_url TEXT,
  is_active   BOOLEAN NOT NULL DEFAULT true,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- 4. store_config — configuración (fila única id = 1)
--    Todo StoreConfig (cupones, plantillas, branding, colores...)
--    se guarda como un solo documento JSONB en `data`.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.store_config (
  id         INTEGER PRIMARY KEY,
  data       JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- ROW LEVEL SECURITY (RLS)
-- ============================================================
-- Activar RLS en las 4 tablas. Sin RLS, la anon key puede hacer
-- CUALQUIER cosa; con RLS y estas políticas, el acceso queda
-- acotado a lo que la app necesita.
--
-- ADVERTENCIA HONESTA: la app usa Firebase Auth, no Supabase Auth,
-- así que Supabase no puede distinguir al admin de un visitante:
-- las escrituras del admin (cambiar estado de un pedido, editar
-- productos o la config) se hacen con la anon key y por eso las
-- políticas de escritura son para el rol `anon`. Alguien que
-- inspeccione el JS podría escribir con esa llave. Para endurecerlo
-- el paso siguiente es mover las escrituras de admin a un backend
-- (Netlify Function con la service_role key) o adoptar Supabase
-- Auth; hasta entonces, estas políticas son el mínimo viable:
-- lectura pública de catálogo/config, escritura de pedidos para
-- que el cliente pueda crear su pedido, y nada de acceso a la
-- service_role key desde el navegador.
-- ============================================================

ALTER TABLE public.products     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders       ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fonts        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_config ENABLE ROW LEVEL SECURITY;

-- products: lectura pública; escritura para el rol anon (la usa el admin desde el navegador)
DROP POLICY IF EXISTS "products_select_public" ON public.products;
CREATE POLICY "products_select_public" ON public.products
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "products_write_anon" ON public.products;
CREATE POLICY "products_write_anon" ON public.products
  FOR ALL USING (true) WITH CHECK (true);

-- orders: cualquiera puede crear un pedido (cliente anónimo) y
-- leer pedidos (seguimiento público por nº de pedido y panel admin);
-- actualizar/borrar lo usa el admin desde el navegador.
DROP POLICY IF EXISTS "orders_insert_anon" ON public.orders;
CREATE POLICY "orders_insert_anon" ON public.orders
  FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "orders_select_anon" ON public.orders;
CREATE POLICY "orders_select_anon" ON public.orders
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "orders_update_anon" ON public.orders;
CREATE POLICY "orders_update_anon" ON public.orders
  FOR UPDATE USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "orders_delete_anon" ON public.orders;
CREATE POLICY "orders_delete_anon" ON public.orders
  FOR DELETE USING (true);

-- fonts: lectura pública; escritura para el rol anon (la usa el admin)
DROP POLICY IF EXISTS "fonts_select_public" ON public.fonts;
CREATE POLICY "fonts_select_public" ON public.fonts
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "fonts_write_anon" ON public.fonts;
CREATE POLICY "fonts_write_anon" ON public.fonts
  FOR ALL USING (true) WITH CHECK (true);

-- store_config: lectura pública (la tienda la necesita);
-- escritura para el rol anon (la usa el admin)
DROP POLICY IF EXISTS "store_config_select_public" ON public.store_config;
CREATE POLICY "store_config_select_public" ON public.store_config
  FOR SELECT USING (true);

DROP POLICY IF EXISTS "store_config_write_anon" ON public.store_config;
CREATE POLICY "store_config_write_anon" ON public.store_config
  FOR ALL USING (true) WITH CHECK (true);
